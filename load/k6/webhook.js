// k6 load test (§15): the HMAC partner webhook.
//   steady: signed deliveries below the per-IP limit (300/min) → all 201, measures processing time
//   burst:  far above the limit from one IP → the limiter answers 429 quickly, nothing breaks
import http from 'k6/http';
import crypto from 'k6/crypto';
import { check } from 'k6';

const BASE = __ENV.BASE_URL || 'http://frontend:8080';

export const options = {
  scenarios: {
    steady: {
      executor: 'constant-arrival-rate',
      rate: 4,
      timeUnit: '1s',
      duration: '45s',
      preAllocatedVUs: 10,
      exec: 'deliver',
      tags: { phase: 'steady' },
    },
    burst: {
      executor: 'constant-arrival-rate',
      rate: 50,
      timeUnit: '1s',
      duration: '10s',
      startTime: '50s',
      preAllocatedVUs: 50,
      exec: 'deliver',
      tags: { phase: 'burst' },
    },
  },
  thresholds: {
    'http_req_duration{phase:steady}': ['p(95)<300'],
    'checks{phase:steady}': ['rate>0.99'],
    // Under the burst every answer must still be a clean 201 or 429, quickly.
    'http_req_duration{phase:burst}': ['p(95)<300'],
    'checks{phase:burst}': ['rate>0.99'],
  },
};

export function setup() {
  const login = http.post(
    `${BASE}/api/v1/auth/login`,
    JSON.stringify({ email: 'admin@untangle.local', password: 'Untangle@2026' }),
    { headers: { 'Content-Type': 'application/json' } },
  );
  const token = login.json('accessToken');
  const code = `k6-${Date.now()}`;
  // A partner whose own limit is high, so only the per-IP limit applies.
  const created = http.post(
    `${BASE}/api/v1/admin/partners`,
    JSON.stringify({ code, name: `Load test ${code}`, rateLimitPerMinute: 10000 }),
    { headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` } },
  );
  check(created, { 'partner created': (r) => r.status === 201 });
  return { code, secret: created.json('secret'), partnerId: created.json('partner.id'), token };
}

export function deliver(data) {
  const body = JSON.stringify({
    customerName: 'Load Test',
    subject: 'Load test complaint',
    description: 'Generated by the k6 webhook load test; safe to close.',
    category: 'GENERAL',
    priority: 'LOW',
  });
  const ts = String(Math.floor(Date.now() / 1000));
  const signature = 'sha256=' + crypto.hmac('sha256', data.secret, `${ts}.${body}`, 'hex');
  const res = http.post(`${BASE}/api/v1/webhooks/partners/tickets`, body, {
    headers: {
      'Content-Type': 'application/json',
      'X-Partner-Id': data.code,
      'X-Event-Id': `evt_${__VU}_${__ITER}_${Date.now()}`,
      'X-Timestamp': ts,
      'X-Signature': signature,
    },
  });
  check(res, { 'created or rate-limited': (r) => r.status === 201 || r.status === 429 });
}

export function teardown(data) {
  // Leave no active load-test partner behind.
  http.patch(
    `${BASE}/api/v1/admin/partners/${data.partnerId}/active`,
    JSON.stringify({ active: false }),
    { headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${data.token}` } },
  );
}
