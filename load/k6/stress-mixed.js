// k6 stress test: a realistic mix of what signed-in people do, at a fixed request rate.
// Run one step:   k6 run stress-mixed.js -e BASE_URL=http://frontend:8080 -e RATE=400
// Run the ladder: make stress   (separate stack with 200k tickets; see docs/scalability.md)
//
// Mix (by weight), modelled on the frontend's polling and clicks (ADR-021):
//   bell unread count 30% · ticket list with filters 25% · ticket detail 20% · timeline 10%
//   dashboard 8% · add a comment (write) 5% · create a ticket (write) 2%
import http from "k6/http";
import { check } from "k6";

const BASE = __ENV.BASE_URL || "http://frontend:8080";
const RATE = Number(__ENV.RATE || 100);
const DURATION = __ENV.DURATION || "30s";
const PASSWORD = "Untangle@2026";
const USERS = [
  "leela.thomas@untangle.local",
  "nikhil.bose@untangle.local",
  "riya.sen@untangle.local",
  "dev.malhotra@untangle.local",
  "tanvi.shah@untangle.local",
  "omar.siddiqui@untangle.local",
];

export const options = {
  scenarios: {
    mixed: {
      executor: "constant-arrival-rate",
      rate: RATE,
      timeUnit: "1s",
      duration: DURATION,
      preAllocatedVUs: Math.min(RATE, 500),
      maxVUs: 3000,
    },
  },
  // Thresholds that never fail: they only make k6 report each endpoint separately.
  // Nothing aborts the run, because the point is to find where it bends.
  thresholds: Object.fromEntries(
    [
      "bell",
      "list",
      "detail",
      "timeline",
      "dashboard",
      "comment",
      "create",
    ].map((e) => [`http_req_duration{endpoint:${e}}`, ["p(95)<600000"]]),
  ),
  summaryTrendStats: ["avg", "med", "p(95)", "p(99)", "max"],
};

const FILTERS = [
  "status=OPEN&status=IN_PROGRESS",
  "priority=CRITICAL&priority=HIGH&sort=slaDueAt,asc",
  "unassigned=true",
  "slaBreached=true",
  "escalated=true&sort=priority,desc",
  "q=refund",
  "mine=true",
  "",
];

const JSON_HEADERS = { "Content-Type": "application/json" };

export function setup() {
  const tokens = USERS.map((email) => {
    const res = http.post(
      `${BASE}/api/v1/auth/login`,
      JSON.stringify({ email, password: PASSWORD }),
      {
        headers: JSON_HEADERS,
      },
    );
    check(res, { "logged in": (r) => r.status === 200 });
    return res.json("accessToken");
  });
  // Ticket ids to open: a mix of unresolved (writable) and any.
  const open = [];
  const any = [];
  for (let page = 0; page < 5; page++) {
    const r1 = http.get(
      `${BASE}/api/v1/tickets?status=OPEN&status=IN_PROGRESS&size=100&page=${page}`,
      {
        headers: { Authorization: `Bearer ${tokens[0]}` },
      },
    );
    r1.json("content").forEach((t) => open.push(t.id));
    const r2 = http.get(`${BASE}/api/v1/tickets?size=100&page=${page * 7}`, {
      headers: { Authorization: `Bearer ${tokens[0]}` },
    });
    r2.json("content").forEach((t) => any.push(t.id));
  }
  return { tokens, open, any };
}

const pick = (list) => list[Math.floor(Math.random() * list.length)];

export default function (data) {
  const auth = { Authorization: `Bearer ${pick(data.tokens)}` };
  const roll = Math.random() * 100;
  let res;
  let endpoint;
  if (roll < 30) {
    endpoint = "bell";
    res = http.get(`${BASE}/api/v1/notifications/unread-count`, {
      headers: auth,
      tags: { endpoint },
    });
  } else if (roll < 55) {
    endpoint = "list";
    const page = Math.floor(Math.random() * 3);
    res = http.get(
      `${BASE}/api/v1/tickets?${pick(FILTERS)}&page=${page}&size=20`,
      {
        headers: auth,
        tags: { endpoint },
      },
    );
  } else if (roll < 75) {
    endpoint = "detail";
    res = http.get(`${BASE}/api/v1/tickets/${pick(data.any)}`, {
      headers: auth,
      tags: { endpoint },
    });
  } else if (roll < 85) {
    endpoint = "timeline";
    res = http.get(`${BASE}/api/v1/tickets/${pick(data.any)}/comments`, {
      headers: auth,
      tags: { endpoint },
    });
  } else if (roll < 93) {
    endpoint = "dashboard";
    res = http.get(`${BASE}/api/v1/dashboard/summary`, {
      headers: auth,
      tags: { endpoint },
    });
  } else if (roll < 98) {
    endpoint = "comment";
    res = http.post(
      `${BASE}/api/v1/tickets/${pick(data.open)}/comments`,
      JSON.stringify({ body: "Stress test update: still investigating." }),
      { headers: { ...auth, ...JSON_HEADERS }, tags: { endpoint } },
    );
  } else {
    endpoint = "create";
    res = http.post(
      `${BASE}/api/v1/tickets`,
      JSON.stringify({
        subject: "Stress test: payment failed",
        description:
          "Generated by the k6 stress test to measure write throughput.",
        customerName: "Load Customer",
        category: "BILLING",
        priority: "MEDIUM",
      }),
      { headers: { ...auth, ...JSON_HEADERS }, tags: { endpoint } },
    );
  }
  check(
    res,
    { "status 2xx": (r) => r.status >= 200 && r.status < 300 },
    { endpoint },
  );
}
