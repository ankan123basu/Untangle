package dev.untangle.ticket.application;

import dev.untangle.agent.domain.Agent;
import dev.untangle.ticket.application.TicketViews.AgentRef;
import dev.untangle.ticket.application.TicketViews.DeniedAction;
import dev.untangle.ticket.application.TicketViews.TicketDetail;
import dev.untangle.ticket.application.TicketViews.TicketSummary;
import dev.untangle.ticket.domain.Ticket;
import dev.untangle.ticket.domain.TicketAction;
import java.time.Duration;
import java.time.Instant;
import java.util.List;
import java.util.Set;
import org.mapstruct.Context;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;
import org.mapstruct.Named;

/**
 * Entity → view mapping, generated by MapStruct at compile time (plain getter calls, no reflection;
 * open {@code target/generated-sources} to read the generated code).
 *
 * <p>{@code unmappedTargetPolicy=ERROR} (pom.xml): if a view gains a field nobody maps, the build
 * fails instead of silently returning {@code null}. "Now" is passed as {@code @Context}, so SLA
 * fields are computed against the injected Clock and are testable.
 */
@Mapper
public interface TicketMapper {

  @Mapping(target = "assignee", source = "assignedAgent")
  @Mapping(target = "slaBreached", source = "ticket", qualifiedByName = "slaBreached")
  TicketSummary toSummary(Ticket ticket, @Context Instant now);

  @Mapping(target = "assignee", source = "ticket.assignedAgent")
  @Mapping(target = "createdBy", source = "ticket.createdBy")
  @Mapping(target = "partnerCode", source = "ticket.partner.code")
  @Mapping(target = "slaBreached", source = "ticket", qualifiedByName = "slaBreached")
  @Mapping(target = "slaRemainingSeconds", source = "ticket", qualifiedByName = "slaRemaining")
  @Mapping(target = "version", source = "ticket.version")
  @Mapping(target = "id", source = "ticket.id")
  @Mapping(target = "createdAt", source = "ticket.createdAt")
  @Mapping(target = "updatedAt", source = "ticket.updatedAt")
  TicketDetail toDetail(
      Ticket ticket,
      Set<TicketAction> allowedActions,
      List<DeniedAction> deniedActions,
      @Context Instant now);

  AgentRef toRef(Agent agent);

  @Named("slaBreached")
  default boolean slaBreached(Ticket ticket, @Context Instant now) {
    return ticket.isSlaBreachedAt(now);
  }

  /** Seconds until the deadline (negative once breached); 0 for resolved/closed tickets. */
  @Named("slaRemaining")
  default long slaRemaining(Ticket ticket, @Context Instant now) {
    return ticket.getStatus().isUnresolved()
        ? Duration.between(now, ticket.getSlaDueAt()).toSeconds()
        : 0;
  }
}
